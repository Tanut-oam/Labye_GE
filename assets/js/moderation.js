//
// ทำงานสองชั้น
//   1. บล็อก  ข้อความหยาบคาย โจมตีบุคคล หรือข้อมูลที่ระบุตัวตนได้
//   2. เตือน  ข้อความที่ส่อว่าผู้เขียนอาจกำลังเสี่ยง ยังโพสต์ได้
//             แต่จะแสดงช่องทางขอความช่วยเหลือให้เห็นก่อน
//
// รายการคำด้านล่างเป็นตัวอย่างสั้น ๆ ต้องขยายเพิ่มก่อนเก็บข้อมูลจริง
// และการกรองด้วยคำอย่างเดียวไม่มีทางครอบคลุมภาษาไทยได้ครบ
// จึงต้องมีคนในกลุ่มคอยดูกระดานระหว่างช่วงทดลองควบคู่กันไป

const BLOCKED = [
  "ไอ้เหี้ย", "สัตว์นรก", "ควาย","เหี้ย","บ้า"
];

// คำที่สื่อถึงความเสี่ยงต่อตัวผู้เขียน ไม่บล็อก แต่ยื่นความช่วยเหลือให้
const RISK = [
  "ไม่อยากอยู่", "อยากหายไป", "ทำร้ายตัวเอง", "อยู่ต่อไม่ไหว"
];

const PHONE = /0\d{8,9}/;
const LINE_ID = /line\s*id/i;

export function moderate(text) {
  const t = text.trim();

  if (t.length < 10) {
    return { ok: false, message: "เขียนอีกนิดได้ไหม อย่างน้อย 10 ตัวอักษร" };
  }

  const hit = BLOCKED.find(w => t.includes(w));
  if (hit) {
    return { ok: false, message: "ข้อความมีคำที่ไม่เหมาะกับพื้นที่นี้ ลองเรียบเรียงใหม่อีกครั้ง" };
  }

  if (PHONE.test(t) || LINE_ID.test(t)) {
    return { ok: false, message: "กระดานนี้เป็นพื้นที่ไม่ระบุตัวตน ไม่ควรใส่เบอร์โทรหรือไอดีติดต่อ" };
  }

  const risky = RISK.some(w => t.includes(w));
  return { ok: true, risky };
}

